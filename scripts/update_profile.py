#!/usr/bin/env python3
"""Rebuild the project tables in profile/README.md from the organization's repositories.

Everything between the ``<!-- repos:start -->`` and ``<!-- repos:end -->`` markers is
generated; the text around them is written by hand and kept.

Which repositories are listed: public, not a fork, not archived, not this repository,
and without the topic ``profile-hide``. Repositories with the topic
``comfyui-custom-node`` go under "ComfyUI custom nodes", the rest under "Tools and
apps". Each row uses the repository's description (its first sentence) and star
count; rows are ordered by stars. A repository that has ``assets/brand/banner.webp``
or ``docs/brand/banner.webp`` also gets its banner above the custom-node table.

Needs ``GITHUB_TOKEN`` (any token that can read the public repositories). Run with
``--check`` to exit 1 when the README is out of date instead of writing it.
"""

import json
import os
import re
import sys
import urllib.error
import urllib.request
from pathlib import Path

ORG = "ComfyAssets"
README = Path(__file__).resolve().parent.parent / "profile" / "README.md"
START, END = "<!-- repos:start -->", "<!-- repos:end -->"
NODE_TOPIC, HIDE_TOPIC = "comfyui-custom-node", "profile-hide"
BANNER_PATHS = ("assets/brand/banner.webp", "docs/brand/banner.webp")
API = "https://api.github.com"


def get(path: str):
    """GET an API path as JSON, or None when it does not exist."""
    request = urllib.request.Request(API + path, headers={"Accept": "application/vnd.github+json"})
    token = os.environ.get("GITHUB_TOKEN")
    if token:
        request.add_header("Authorization", f"Bearer {token}")
    try:
        with urllib.request.urlopen(request, timeout=30) as response:  # nosec B310 (fixed https host)
            return json.load(response)
    except urllib.error.HTTPError as error:
        if error.code == 404:
            return None
        raise


def listed_repositories() -> list[dict]:
    repos, page = [], 1
    while True:
        batch = get(f"/orgs/{ORG}/repos?type=public&per_page=100&page={page}") or []
        repos += batch
        if len(batch) < 100:
            break
        page += 1
    return [
        repo
        for repo in repos
        if not (repo["fork"] or repo["archived"] or repo["private"])
        and repo["name"] != ".github"
        and HIDE_TOPIC not in repo.get("topics", [])
    ]


def first_sentence(text: str) -> str:
    text = " ".join((text or "").split())
    match = re.match(r"(.+?[.!?])(\s|$)", text)
    sentence = match.group(1) if match else text
    return sentence.replace("|", "\\|")


def banner_url(repo: dict):
    for path in BANNER_PATHS:
        if get(f"/repos/{ORG}/{repo['name']}/contents/{path}") is not None:
            branch = repo["default_branch"]
            return f"https://raw.githubusercontent.com/{ORG}/{repo['name']}/{branch}/{path}"
    return None


def table(repos: list[dict]) -> list[str]:
    rows = ["| Project | What it does | Stars |", "| --- | --- | ---: |"]
    for repo in sorted(repos, key=lambda r: (-r["stargazers_count"], r["name"].lower())):
        rows.append(
            f"| [**{repo['name']}**]({repo['html_url']}) | {first_sentence(repo['description'])} "
            f"| {repo['stargazers_count']} |"
        )
    return rows


def render(repos: list[dict], banners: dict[str, str]) -> str:
    nodes = [repo for repo in repos if NODE_TOPIC in repo.get("topics", [])]
    others = [repo for repo in repos if NODE_TOPIC not in repo.get("topics", [])]
    lines = ["<!-- Generated by scripts/update_profile.py; edit the repositories, not this block. -->", ""]
    if nodes:
        lines.append("## ComfyUI custom nodes")
        lines.append("")
        featured = [repo for repo in sorted(nodes, key=lambda r: -r["stargazers_count"]) if repo["name"] in banners]
        if featured:
            width = "49%" if len(featured) > 1 else "100%"
            for repo in featured:
                lines.append(
                    f'<a href="{repo["html_url"]}"><img src="{banners[repo["name"]]}" '
                    f'alt="{repo["name"]}" width="{width}"></a>'
                )
            lines.append("")
        lines += table(nodes) + [""]
    if others:
        lines += ["## Tools and apps", ""] + table(others) + [""]
    return "\n".join(lines)


def updated(readme: str, block: str) -> str:
    if readme.count(START) != 1 or readme.count(END) != 1 or readme.index(START) > readme.index(END):
        raise SystemExit(f"{README}: needs exactly one {START} ... {END} pair")
    head, rest = readme.split(START, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{START}\n{block}\n{END}{tail}"


def main(argv: list[str]) -> int:
    repos = listed_repositories()
    banners = {
        repo["name"]: url
        for repo in repos
        if NODE_TOPIC in repo.get("topics", []) and (url := banner_url(repo))
    }
    old = README.read_text(encoding="utf-8")
    new = updated(old, render(repos, banners))
    if new == old:
        print("profile/README.md is up to date")
        return 0
    if "--check" in argv:
        print("profile/README.md is out of date")
        return 1
    README.write_text(new, encoding="utf-8")
    print(f"profile/README.md updated: {len(repos)} repositories")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
